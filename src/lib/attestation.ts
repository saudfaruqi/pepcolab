// src/lib/attestation.ts
//
// CHECKOUT RESEARCH ATTESTATION (brief A10).
//
// Before payment the customer must tick ATTESTATION_TEXT. The browser sends
// the time they ticked it two ways, so it reaches the order whichever
// arrives:
//   1. in STRABL's cart.extra as `researchAttestedAt` (echoed back on the
//      webhook alongside `ref`), and
//   2. to POST /api/checkout/attest, which stores it here under the checkout
//      reference for the webhook to collect with takeAttestation().
//
// Server-only (Redis). The text itself is also exported for the client
// component and for the order/CRM records, so the wording that was agreed to
// is always the wording stored.
import { redis } from '@/lib/redis'

import { ATTESTATION_TEXT, ATTESTATION_VERSION } from '@/lib/attestationText'

export { ATTESTATION_TEXT, ATTESTATION_VERSION }

const KEY = (ref: string) => `attest:${ref}`
const TTL_SECONDS = 60 * 60 * 24 * 3

/** A checkout reference as generated by lib/analytics.ts trackBeginCheckout(). */
export function isCheckoutRef(ref: unknown): ref is string {
  return typeof ref === 'string' && /^PL-\d{10,16}-[A-Z0-9]{4,10}$/.test(ref)
}

/** A plausible attestation time: valid ISO, not in the future, not older than a day. */
export function cleanAttestedAt(iso: unknown, now = Date.now()): string | null {
  if (typeof iso !== 'string') return null
  const t = new Date(iso).getTime()
  if (!Number.isFinite(t)) return null
  if (t > now + 5 * 60 * 1000 || now - t > 24 * 60 * 60 * 1000) return null
  return new Date(t).toISOString()
}

export async function saveAttestation(ref: string, iso: string): Promise<void> {
  // First write wins: a later call can never move the recorded time.
  await redis.set(KEY(ref), `${iso}|${ATTESTATION_VERSION}`, { ex: TTL_SECONDS, nx: true })
}

/** Reads and clears the stored attestation time for a checkout, if any. */
export async function takeAttestation(ref: string): Promise<string | null> {
  if (!isCheckoutRef(ref)) return null
  try {
    const raw = await redis.get<string>(KEY(ref))
    if (!raw) return null
    await redis.del(KEY(ref))
    const iso = String(raw).split('|')[0]
    return Number.isFinite(new Date(iso).getTime()) ? iso : null
  } catch (err) {
    console.error('[attestation] read failed:', err)
    return null
  }
}
